"""Hidden test vectors for t01, from one Python reference model.

Writes vectors.h (C) and vectors.rs (Rust) from the same cases, so both
languages are judged against the same behaviour. Every case names the spec
sentence (R1..R7) it checks. `fxm.py self-test` regenerates these in memory and
fails if the committed files differ.

FXM-HIDDEN-CANARY-t01 (this marker must never reach a model prompt)
"""
import pathlib
import random
import sys

CANARY = "FXM-HIDDEN-CANARY-t01"
CAPACITY = 16
SEED = 20261029
NEW, PUSH, POP, PEEK, LEN = 0, 1, 2, 3, 4


class Model:
    def __init__(self):
        self.q = []

    def step(self, op, arg):
        """Returns (ok, val) as the spec requires."""
        if op == NEW:
            self.q = []
            return 1, 0
        if op == PUSH:
            if len(self.q) < CAPACITY:
                self.q.append(arg)
                return 1, 0
            return 0, 0
        if op == POP:
            return (1, self.q.pop(0)) if self.q else (0, 0)
        if op == PEEK:
            return (1, self.q[0]) if self.q else (0, 0)
        if op == LEN:
            return 1, len(self.q)
        raise ValueError(op)


def run(ops):
    m = Model()
    return [(op, arg, *m.step(op, arg)) for op, arg in [(NEW, 0), *ops]]


def cases():
    out = []
    out.append(("new_is_empty", "R1", run([(LEN, 0), (POP, 0), (PEEK, 0)])))
    out.append(("push_one_pop_one", "R2 R4", run([(PUSH, 7), (LEN, 0), (POP, 0), (LEN, 0)])))
    out.append(("peek_does_not_remove", "R5", run([(PUSH, 9), (PEEK, 0), (PEEK, 0), (LEN, 0), (POP, 0)])))
    fill = [(PUSH, 100 + i) for i in range(CAPACITY)]
    out.append(("fill_to_capacity", "R2 R7", run([*fill, (LEN, 0)])))
    out.append(("push_on_full_rejected_and_unchanged", "R3",
                run([*fill, (PUSH, 255), (LEN, 0), *[(POP, 0)] * CAPACITY, (POP, 0)])))
    out.append(("pop_on_empty_changes_nothing", "R4", run([(POP, 0), (PUSH, 3), (LEN, 0), (POP, 0)])))
    wrap = []
    for k in range(5):
        wrap += [(PUSH, (k * 11 + j) & 0xFF) for j in range(10)] + [(POP, 0)] * 10
    out.append(("fifo_across_wraparounds", "R6", run(wrap)))
    out.append(("full_then_drain_then_full", "R3 R6",
                run([*fill, *[(POP, 0)] * CAPACITY, *[(PUSH, i) for i in range(CAPACITY)], (PUSH, 1),
                     *[(POP, 0)] * CAPACITY])))
    rng = random.Random(SEED)
    for n in range(40):
        ops = []
        for _ in range(64):
            r = rng.random()
            if r < 0.5:
                ops.append((PUSH, rng.randrange(256)))
            elif r < 0.8:
                ops.append((POP, 0))
            elif r < 0.9:
                ops.append((PEEK, 0))
            else:
                ops.append((LEN, 0))
        out.append((f"random_sequence_{n:02d}", "R2 R3 R4 R5 R6 R7", run(ops)))
    return out


def generate():
    cs = cases()
    steps, table, start = [], [], 0
    for name, req, st in cs:
        steps += st
        table.append((name, req, start, len(st)))
        start += len(st)
    head = (f"/* {CANARY}: generated by gen_vectors.py; do not edit. Hidden from the model. */\n")
    c = [head, "#ifndef FXM_VECTORS_H\n#define FXM_VECTORS_H\n#include <stdint.h>\n",
         "typedef struct { uint8_t op; uint8_t arg; uint8_t ok; uint8_t val; } fxm_step_t;\n",
         "typedef struct { const char *name; const char *req; uint16_t start; uint16_t len; } fxm_case_t;\n",
         "static const fxm_step_t FXM_STEPS[] = {\n"]
    c += [f"    {{{o}U, {a}U, {k}U, {v}U}},\n" for o, a, k, v in steps]
    c += ["};\nstatic const fxm_case_t FXM_CASES[] = {\n"]
    c += [f'    {{"{n}", "{r}", {s}U, {ln}U}},\n' for n, r, s, ln in table]
    c += [f"}};\n#define FXM_N_CASES {len(table)}U\n#endif\n"]
    rs = [f"// {CANARY}: generated by gen_vectors.py; do not edit. Hidden from the model.\n",
          "#[rustfmt::skip]\npub const STEPS: &[(u8, u8, u8, u8)] = &[\n"]
    rs += [f"    ({o}, {a}, {k}, {v}),\n" for o, a, k, v in steps]
    rs += ["];\n#[rustfmt::skip]\npub const CASES: &[(&str, &str, usize, usize)] = &[\n"]
    rs += [f'    ("{n}", "{r}", {s}, {ln}),\n' for n, r, s, ln in table]
    rs += ["];\n"]
    return {"vectors.h": "".join(c), "vectors.rs": "".join(rs)}


if __name__ == "__main__":
    here = pathlib.Path(__file__).parent
    for name, text in generate().items():
        (here / name).write_text(text)
    print(f"wrote {len(generate())} files", file=sys.stderr)
