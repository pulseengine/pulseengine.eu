"""Hidden test vectors for t02, from one Python reference model.

Writes vectors.h (C) and vectors.rs (Rust) from the same cases, so both
languages are judged against the same behaviour. Every vector names the spec
sentence (Q1..Q5) it checks. `fxm.py self-test` regenerates these in memory and
fails if the committed files differ.

FXM-HIDDEN-CANARY-t02 (this marker must never reach a model prompt)
"""
import pathlib
import random
import sys

CANARY = "FXM-HIDDEN-CANARY-t02"
SEED = 20261029
ADD, SUB, MUL, NEG, ABS = 0, 1, 2, 3, 4
REQ = {ADD: "Q1", SUB: "Q2", MUL: "Q3", NEG: "Q4", ABS: "Q5"}
LO, HI = -32768, 32767
EDGES = [LO, LO + 1, -16384, -2, -1, 0, 1, 2, 16383, 16384, HI - 1, HI]


def clamp(x):
    return max(LO, min(HI, x))


def ref(op, a, b):
    if op == ADD:
        return clamp(a + b)
    if op == SUB:
        return clamp(a - b)
    if op == MUL:
        return clamp((a * b + 16384) // 32768)  # Python // is floor division
    if op == NEG:
        return clamp(-a)
    if op == ABS:
        return clamp(abs(a))
    raise ValueError(op)


def vectors():
    out = []
    for op in (ADD, SUB, MUL):
        out += [(op, a, b) for a in EDGES for b in EDGES]
    out += [(op, a, 0) for op in (NEG, ABS) for a in EDGES]
    # Rounding ties for Q3: products that are exact odd multiples of 16384.
    out += [(MUL, a, b) for a, b in [(1, 16384), (-1, 16384), (3, 16384), (-3, 16384), (16384, 16384),
                                     (-16384, 16384), (2, 8192), (-2, 8192)]]
    rng = random.Random(SEED)
    for op in (ADD, SUB, MUL, NEG, ABS):
        out += [(op, rng.randint(LO, HI), rng.randint(LO, HI) if op <= MUL else 0) for _ in range(400)]
    return [(op, a, b, ref(op, a, b)) for op, a, b in out]


def generate():
    vs = vectors()
    c = [f"/* {CANARY}: generated by gen_vectors.py; do not edit. Hidden from the model. */\n",
         "#ifndef FXM_VECTORS_H\n#define FXM_VECTORS_H\n#include <stdint.h>\n",
         "typedef struct { uint8_t op; int32_t a; int32_t b; int32_t want; } fxm_vec_t;\n",
         "static const fxm_vec_t FXM_VECS[] = {\n"]
    c += [f"    {{{op}U, {a}, {b}, {w}}},\n" for op, a, b, w in vs]
    c += [f"}};\n#define FXM_N_VECS {len(vs)}U\n#endif\n"]
    rs = [f"// {CANARY}: generated by gen_vectors.py; do not edit. Hidden from the model.\n",
          "#[rustfmt::skip]\npub const VECS: &[(u8, i32, i32, i32)] = &[\n"]
    rs += [f"    ({op}, {a}, {b}, {w}),\n" for op, a, b, w in vs]
    rs += ["];\n"]
    return {"vectors.h": "".join(c), "vectors.rs": "".join(rs)}


if __name__ == "__main__":
    here = pathlib.Path(__file__).parent
    for name, text in generate().items():
        (here / name).write_text(text)
    print(f"wrote {len(generate())} files", file=sys.stderr)
